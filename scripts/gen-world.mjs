import { readFileSync, writeFileSync } from "node:fs";
import { geoEquirectangular, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const topo = JSON.parse(
  readFileSync("node_modules/world-atlas/countries-110m.json", "utf8"),
);
const fc = feature(topo, topo.objects.countries);
const W = 1000;
const H = 500;
const projection = geoEquirectangular()
  .scale(W / (2 * Math.PI))
  .translate([W / 2, H / 2]);
const path = geoPath(projection).digits(1);

const out = [];
for (const f of fc.features) {
  const d = path(f);
  if (!d) continue;
  out.push([f.properties.name, d]);
}
writeFileSync(
  "src/lib/world-paths.ts",
  `// Generated by scripts/gen-world.mjs - equirectangular 1000x500\nexport const WORLD_PATHS: [string, string][] = ${JSON.stringify(out)};\n`,
);
console.log(out.length, "countries;", out.map((o) => o[0]).join("|"));
